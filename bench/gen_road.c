/*
 * Generates a large synthetic road network for speed tests, on standard output.
 * Usage: gen_road SIDE SEED
 *
 * The network is a jittered SIDE x SIDE grid over rolling hills, with mixed speed
 * limits and some one-way and closed roads, so it has SIDE * SIDE nodes. A given
 * seed always gives the same file on the same C library.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#define SPACING_M 100.0
#define JITTER_M 30.0

enum { MIN_SIDE = 2, MAX_SIDE = 2000 };

typedef struct {
    double x_m;
    double y_m;
} Position;

static double random_between(double low, double high)
{
    return low + rand() / (RAND_MAX + 1.0) * (high - low);
}

/* Coordinates are written with 3 decimals, so distances must use those values. */
static double round_to_mm(double value)
{
    return round(value * 1000.0) / 1000.0;
}

static void write_road(const Position *positions, int a, int b)
{
    static const int limits[] = {20, 30, 40, 60};
    double straight_m = hypot(positions[b].x_m - positions[a].x_m,
                              positions[b].y_m - positions[a].y_m);
    /* Rounds up, with a margin, so a road is never shorter than the straight line. */
    double length_m = ceil(straight_m * random_between(1.0, 1.3) * 1000.0) / 1000.0 + 0.001;
    printf("E %d %d %.3f %d %d %d\n", a, b, length_m, limits[rand() % 4],
           rand() % 100 < 10, rand() % 100 < 5);
}

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "Usage: %s SIDE SEED\n", argv[0]);
        return 1;
    }
    int side = atoi(argv[1]);
    if (side < MIN_SIDE || side > MAX_SIDE) {
        fprintf(stderr, "error: SIDE must be from %d to %d\n", MIN_SIDE, MAX_SIDE);
        return 1;
    }
    srand((unsigned)atoi(argv[2]));

    Position *positions = malloc((size_t)side * (size_t)side * sizeof(Position));
    if (positions == NULL) {
        fprintf(stderr, "error: out of memory\n");
        return 1;
    }

    printf("# Generated by gen_road: side %d, seed %s\n", side, argv[2]);
    for (int id = 0; id < side * side; id++) {
        double x_m = round_to_mm((id % side) * SPACING_M + random_between(-JITTER_M, JITTER_M));
        double y_m = round_to_mm((id / side) * SPACING_M + random_between(-JITTER_M, JITTER_M));
        double elevation_m = 60 * sin(x_m / 700) + 40 * cos(y_m / 500) + random_between(-4, 4);
        positions[id] = (Position){x_m, y_m};
        printf("N %d N%d %.3f %.3f %.3f\n", id, id, x_m, y_m, elevation_m);
    }
    for (int id = 0; id < side * side; id++) {
        int col = id % side;
        int row = id / side;
        if (col + 1 < side) {
            write_road(positions, id, id + 1);
        }
        if (row + 1 < side) {
            write_road(positions, id, id + side);
        }
    }

    free(positions);
    /* A full disk may only show up here, and a truncated map must not pass as good. */
    if (fflush(stdout) != 0 || ferror(stdout)) {
        fprintf(stderr, "error: cannot write output\n");
        return 1;
    }
    return 0;
}
